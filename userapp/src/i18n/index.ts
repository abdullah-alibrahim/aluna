const dictionaries = { ar, en };

type Dict = typeof ar;

function getByPath(obj: any, path: string): string | undefined {
  return path.split('.').reduce((acc, key) => (acc == null ? undefined : acc[key]), obj);
}

export const setLocale = (locale: Locale) => {
  currentLocale = locale;
};

export const getLocale = () => currentLocale;

export const t = (key: string, fallback?: string): string => {
  const value = getByPath(dictionaries[currentLocale], key) ?? getByPath(dictionaries.ar, key);
  return (typeof value === 'string' ? value : fallback || key);
};

export const paymentStatusLabel = (status?: string) => {
  switch (status) {
    case 'paid': return t('payment.paid');
    case 'pending': return t('payment.pending');
    case 'unpaid': return t('payment.unpaid');
    case 'cancelled': return t('payment.cancelled');
    default: return status || t('payment.pending');
  }
};

export const paymentMethodLabel = (method?: string) => {
  switch (method) {
    case 'stripe': return t('payment.stripe');
    case 'cash': return t('payment.cash');
    default: return method || t('payment.cash');
  }
};

export const bookingStatusLabel = (status?: string) => {
  switch (status) {
    case 'pending': return t('bookingStatus.pending');
    case 'confirmed': return t('bookingStatus.confirmed');
    case 'completed': return t('bookingStatus.completed');
    case 'cancelled': return t('bookingStatus.cancelled');
    case 'no_show': return t('bookingStatus.no_show');
    default: return status || '';
  }
};

export type { Dict };
